def _load_json(path: Path) -> dict[str, Any]:
    with path.open() as f:
        return json.load(f)


def _schema_type(series: pd.Series) -> str:
    if is_bool_dtype(series):
        return "sc:Boolean"
    if is_integer_dtype(series):
        return "sc:Integer"
    if is_float_dtype(series):
        return "sc:Float"
    if is_numeric_dtype(series):
        return "sc:Number"
    return "sc:Text"


def _field_description(record_set_name: str, column_name: str) -> str:
    if column_name == "t":
        return f"Timestamp column for the {record_set_name} split."
    if column_name == "y":
        return f"Target column for the {record_set_name} split."
    if column_name.startswith("ds_"):
        return f"Latent sufficient-statistic feature `{column_name}`."
    if column_name.startswith("z_num_"):
        return f"Original numeric row-local feature `{column_name}`."
    if column_name.startswith("z_cat_"):
        return f"Original categorical row-local feature `{column_name}`."
    if column_name.startswith("num_"):
        return f"Anonymized observable numeric feature `{column_name}`."
    if column_name.startswith("cat_"):
        return f"Anonymized observable categorical or entity feature `{column_name}`."
    return f"Column `{column_name}` from the {record_set_name} split."


def _file_object(file_id: str, path: Path, rel_to: Path) -> dict[str, Any]:
    relative_path = path.relative_to(rel_to).as_posix()
    sha256 = hashlib.sha256(path.read_bytes()).hexdigest()
    safe_name = relative_path
    for old, new in (
        ("/", "__"),
        ("+", "_plus_"),
        (":", "_"),
        (" ", "_"),
        ("`", "_"),
        ("(", "_"),
        (")", "_"),
        ("[", "_"),
        ("]", "_"),
        ("{", "_"),
        ("}", "_"),
        (",", "_"),
        (";", "_"),
    ):
        safe_name = safe_name.replace(old, new)
    return {
        "@type": "sc:FileObject",
        "@id": file_id,
        "name": safe_name,
        "contentUrl": relative_path,
        "encodingFormat": "application/json" if path.suffix == ".json" else "text/csv",
        "sha256": sha256,
    }


def _csv_record_set(
    record_set_id: str,
    file_id: str,
    csv_path: Path,
) -> dict[str, Any]:
    df = pd.read_csv(csv_path)
    fields: list[dict[str, Any]] = []
    for column_name in df.columns:
        fields.append(
            {
                "@type": "cr:Field",
                "@id": f"{record_set_id}/{column_name}",
                "name": column_name,
                "description": _field_description(record_set_id, column_name),
                "dataType": _schema_type(df[column_name]),
                "source": {
                    "fileObject": {"@id": file_id},
                    "extract": {"column": column_name},
                },
            }
        )
    return {
        "@type": "cr:RecordSet",
        "@id": record_set_id,
        "name": record_set_id,
        "description": f"Structured rows extracted from `{csv_path.name}`.",
        "field": fields,
    }


def _scalar_schema_type(value: Any) -> str:
    if isinstance(value, bool):
        return "sc:Boolean"
    if isinstance(value, int) and not isinstance(value, bool):
        return "sc:Integer"
    if isinstance(value, float):
        return "sc:Float"
    if isinstance(value, list):
        return "sc:Text"
    if isinstance(value, dict):
        return "sc:Text"
    return "sc:Text"


def _json_record_set(record_set_id: str, name: str, description: str, data: dict[str, Any]) -> dict[str, Any]:
    fields: list[dict[str, Any]] = []
    row: dict[str, Any] = {}
    for key, value in data.items():
        field_id = f"{record_set_id}/{key}"
        fields.append(
            {
                "@type": "cr:Field",
                "@id": field_id,
                "name": key,
                "description": f"Metadata field `{key}` from `{name}`.",
                "dataType": _scalar_schema_type(value),
            }
        )
        row[field_id] = json.dumps(value, sort_keys=True) if isinstance(value, (dict, list)) else value
    return {
        "@type": "cr:RecordSet",
        "@id": record_set_id,
        "name": name,
        "description": description,
        "field": fields,
        "data": [row],
    }


def _infer_suite(dataset_dir: Path) -> str:
    parts = dataset_dir.parts
    for name in ("no_drift", "drift", "n_dyn", "random_samples"):
        if name in parts:
            return name
    return "unknown"


def _iter_dataset_dirs(root: Path) -> list[Path]:
    return sorted(path.parent for path in root.rglob("config_used.json"))


def _iter_family_dirs(root: Path) -> list[Path]:
    families: list[Path] = []
    for path in sorted(root.iterdir()):
        if path.is_dir() and any(path.rglob("config_used.json")):
            families.append(path)
    return families


def build_croissant(
    dataset_dir: Path,
    dataset_name: str,
    dataset_description: str,
    dataset_url: str,
    license_url: str,
) -> dict[str, Any]:
    dataset_dir = dataset_dir.resolve()
    config = _load_json(dataset_dir / "config_used.json")
    metrics = _load_json(dataset_dir / "metrics.json")

    distributions = [
        _file_object("observables-train-file", dataset_dir / "observables_train.csv", dataset_dir),
        _file_object("observables-test-file", dataset_dir / "observables_test.csv", dataset_dir),
        _file_object("optimal-train-file", dataset_dir / "optimal_train.csv", dataset_dir),
        _file_object("optimal-test-file", dataset_dir / "optimal_test.csv", dataset_dir),
        _file_object("y-train-file", dataset_dir / "y_train.csv", dataset_dir),
        _file_object("y-test-file", dataset_dir / "y_test.csv", dataset_dir),
        _file_object("config-file", dataset_dir / "config_used.json", dataset_dir),
        _file_object("metrics-file", dataset_dir / "metrics.json", dataset_dir),
    ]

    record_sets = [
        _csv_record_set("observables_train", "observables-train-file", dataset_dir / "observables_train.csv"),
        _csv_record_set("observables_test", "observables-test-file", dataset_dir / "observables_test.csv"),
        _csv_record_set("optimal_train", "optimal-train-file", dataset_dir / "optimal_train.csv"),
        _csv_record_set("optimal_test", "optimal-test-file", dataset_dir / "optimal_test.csv"),
        _csv_record_set("targets_train", "y-train-file", dataset_dir / "y_train.csv"),
        _csv_record_set("targets_test", "y-test-file", dataset_dir / "y_test.csv"),
        _json_record_set(
            "benchmark_config",
            "benchmark_config",
            "Run-level generation metadata from `config_used.json`.",
            config,
        ),
        _json_record_set(
            "baseline_metrics",
            "baseline_metrics",
            "Run-level baseline metrics from `metrics.json`.",
            metrics,
        ),
    ]

    suite_name = _infer_suite(dataset_dir)
    dynamic_name = config.get("dynamic_key", config.get("dynamic", "unknown"))
    entities_dim = config.get("entities_dim", "unknown")
    task = config.get("task", "classification")

    return {
        "@context": {
            "@language": "en",
            "@vocab": "https://schema.org/",
            "cr": "http://mlcommons.org/croissant/",
            "sc": "https://schema.org/",
            "rai": "http://mlcommons.org/croissant/RAI/",
            "dct": "http://purl.org/dc/terms/",
        },
        "@type": "sc:Dataset",
        "name": dataset_name,
        "description": dataset_description,
        "url": dataset_url,
        "license": license_url,
        "citation": "TabGen benchmark run metadata generated from the released dataset artifacts.",
        "datePublished": DEFAULT_DATE_PUBLISHED,
        "version": "0.1.0",
        "conformsTo": CONFORMS_TO,
        "keywords": [
            "tabular benchmark",
            "synthetic dataset",
            "temporal evaluation",
            f"suite:{suite_name}",
            f"task:{task}",
            f"dynamic:{dynamic_name}",
            f"entities_dim:{entities_dim}",
        ],
        **_rai_fields(),
        "distribution": distributions,
        "recordSet": record_sets,
    }


def _record_set_from_rows(
    record_set_id: str,
    name: str,
    description: str,
    rows: list[dict[str, Any]],
) -> dict[str, Any]:
    keys: list[str] = []
    for row in rows:
        for key in row:
            if key not in keys:
                keys.append(key)
    fields: list[dict[str, Any]] = []
    normalized_rows: list[dict[str, Any]] = []
    for key in keys:
        sample = next((row[key] for row in rows if key in row), "")
        fields.append(
            {
                "@type": "cr:Field",
                "@id": f"{record_set_id}/{key}",
                "name": key,
                "description": f"Field `{key}` in `{name}`.",
                "dataType": _scalar_schema_type(sample),
            }
        )
    for row in rows:
        normalized: dict[str, Any] = {}
        for key in keys:
            value = row.get(key, "")
            normalized[f"{record_set_id}/{key}"] = (
                json.dumps(value, sort_keys=True) if isinstance(value, (dict, list)) else value
            )
        normalized_rows.append(normalized)
    return {
        "@type": "cr:RecordSet",
        "@id": record_set_id,
        "name": name,
        "description": description,
        "field": fields,
        "data": normalized_rows,
    }


def _run_row(family_dir: Path, dataset_dir: Path) -> dict[str, Any]:
    config = _load_json(dataset_dir / "config_used.json")
    rel_dir = dataset_dir.relative_to(family_dir).as_posix()
    row: dict[str, Any] = {
        "run_id": rel_dir.replace("/", "__"),
        "relative_dir": rel_dir,
        "suite": _infer_suite(dataset_dir),
        "task": config.get("task", "classification"),
        "dynamic_key": config.get("dynamic_key", config.get("dynamic", "unknown")),
        "entities_dim": config.get("entities_dim", ""),
        "n_num": config.get("n_num", ""),
        "n_cat": config.get("n_cat", ""),
        "n_samples": config.get("n_samples", ""),
        "c_dyn": config.get("c_dyn", ""),
        "c_noise": config.get("c_noise", ""),
        "observables_train_path": f"{rel_dir}/observables_train.csv",
        "observables_test_path": f"{rel_dir}/observables_test.csv",
        "optimal_train_path": f"{rel_dir}/optimal_train.csv",
        "optimal_test_path": f"{rel_dir}/optimal_test.csv",
        "y_train_path": f"{rel_dir}/y_train.csv",
        "y_test_path": f"{rel_dir}/y_test.csv",
        "config_path": f"{rel_dir}/config_used.json",
        "metrics_path": f"{rel_dir}/metrics.json",
    }
    for extra_key in ("drift", "dependencies_used", "sample_seed", "seed"):
        if extra_key in config:
            row[extra_key] = config[extra_key]
    return row


def _metrics_row(family_dir: Path, dataset_dir: Path) -> dict[str, Any]:
    metrics = _load_json(dataset_dir / "metrics.json")
    rel_dir = dataset_dir.relative_to(family_dir).as_posix()
    row: dict[str, Any] = {
        "run_id": rel_dir.replace("/", "__"),
        "relative_dir": rel_dir,
    }
    row.update(metrics)
    return row


def build_family_croissant(
    family_dir: Path,
    dataset_name: str,
    dataset_description: str,
    dataset_url: str,
    license_url: str,
) -> dict[str, Any]:
    family_dir = family_dir.resolve()
    dataset_dirs = _iter_dataset_dirs(family_dir)
    distributions: list[dict[str, Any]] = []
    run_rows: list[dict[str, Any]] = []
    metrics_rows: list[dict[str, Any]] = []
    for idx, dataset_dir in enumerate(dataset_dirs):
        rel_dir = dataset_dir.relative_to(family_dir).as_posix()
        run_rows.append(_run_row(family_dir, dataset_dir))
        metrics_rows.append(_metrics_row(family_dir, dataset_dir))
        for file_name in (
            "observables_train.csv",
            "observables_test.csv",
            "optimal_train.csv",
            "optimal_test.csv",
            "y_train.csv",
            "y_test.csv",
            "config_used.json",
            "metrics.json",
        ):
            file_path = dataset_dir / file_name
            distributions.append(
                _file_object(
                    f"run-{idx}-{file_name.replace('.', '-').replace('_', '-')}",
                    file_path,
                    family_dir,
                )
            )
    family_name = family_dir.name
    return {
        "@context": {
            "@language": "en",
            "@vocab": "https://schema.org/",
            "cr": "http://mlcommons.org/croissant/",
            "sc": "https://schema.org/",
            "rai": "http://mlcommons.org/croissant/RAI/",
            "dct": "http://purl.org/dc/terms/",
        },
        "@type": "sc:Dataset",
        "name": dataset_name,
        "description": dataset_description,
        "url": dataset_url,
        "license": license_url,
        "citation": "TabGen benchmark family metadata generated from the released dataset artifacts.",
        "datePublished": DEFAULT_DATE_PUBLISHED,
        "version": "0.1.0",
        "conformsTo": CONFORMS_TO,
        "keywords": [
            "tabular benchmark",
            "synthetic dataset",
            "temporal evaluation",
            f"family:{family_name}",
            f"n_runs:{len(dataset_dirs)}",
        ],
        **_rai_fields(),
        "distribution": distributions,
        "recordSet": [
            _record_set_from_rows(
                "benchmark_runs",
                "benchmark_runs",
                "Run-level manifest for all generated datasets in this benchmark family.",
                run_rows,
            ),
            _record_set_from_rows(
                "baseline_metrics",
                "baseline_metrics",
                "Run-level baseline metric summary for this benchmark family.",
                metrics_rows,
            ),
        ],
    }


def _default_name_and_description(dataset_dir: Path) -> tuple[str, str]:
    config = _load_json(dataset_dir / "config_used.json")
    default_name = (
        f"tabgen_{config.get('task', 'classification')}_"
        f"{config.get('dynamic_key', config.get('dynamic', 'benchmark'))}_"
        f"dim{config.get('entities_dim', 'x')}"
    )
    default_description = (
        "Synthetic temporal tabular benchmark generated by TabGen, "
        "with observable and optimal feature views, chronological train/test splits, "
        "and saved baseline metrics."
    )
    return default_name, default_description


def _default_family_name_and_description(family_dir: Path) -> tuple[str, str]:
    family_name = family_dir.name
    default_name = f"tabgen_{family_name}_benchmark_family"
    default_description = (
        f"TabGen synthetic tabular benchmark family `{family_name}`, "
        "containing multiple generated runs with observable and optimal views, "
        "chronological train/test splits, configuration metadata, and baseline metrics."
    )
    return default_name, default_description


def _write_croissant(
    dataset_dir: Path,
    output: Path | None,
    dataset_name: str | None,
    dataset_description: str | None,
    dataset_url: str,
    license_url: str,
) -> Path:
    default_name, default_description = _default_name_and_description(dataset_dir)
    output_path = output or (dataset_dir / "croissant.json")
    croissant = build_croissant(
        dataset_dir=dataset_dir,
        dataset_name=dataset_name or default_name,
        dataset_description=dataset_description or default_description,
        dataset_url=dataset_url,
        license_url=license_url,
    )
    output_path.write_text(json.dumps(croissant, indent=2) + "\n")
    return output_path


def _write_family_croissant(
    family_dir: Path,
    output: Path | None,
    dataset_name: str | None,
    dataset_description: str | None,
    dataset_url: str,
    license_url: str,
) -> Path:
    default_name, default_description = _default_family_name_and_description(family_dir)
    output_path = output or (family_dir / "croissant.json")
    croissant = build_family_croissant(
        family_dir=family_dir,
        dataset_name=dataset_name or default_name,
        dataset_description=dataset_description or default_description,
        dataset_url=dataset_url,
        license_url=license_url,
    )
    output_path.write_text(json.dumps(croissant, indent=2) + "\n")
    return output_path


def main() -> None:
    ap = argparse.ArgumentParser("tabgen-generate-croissant")
    ap.add_argument("--dataset-dir", type=Path, default=None, help="Generated TabGen run directory")
    ap.add_argument("--family-dir", type=Path, default=None, help="Root directory for one benchmark family")
    ap.add_argument("--suite-dir", type=Path, default=None, help="Root directory containing multiple benchmark families")
    ap.add_argument("--output", type=Path, default=None, help="Output Croissant JSON-LD path")
    ap.add_argument("--name", type=str, default=None, help="Dataset display name")
    ap.add_argument("--description", type=str, default=None, help="Dataset description")
    ap.add_argument("--url", type=str, default="https://example.com/tabgen", help="Canonical dataset URL")
    ap.add_argument("--license", type=str, default=DEFAULT_LICENSE, help="Dataset license URL")
    args = ap.parse_args()
    mode_count = sum(value is not None for value in (args.dataset_dir, args.family_dir, args.suite_dir))
    if mode_count != 1:
        raise SystemExit("Provide exactly one of --dataset-dir, --family-dir, or --suite-dir")

    if args.dataset_dir is not None:
        dataset_dir = args.dataset_dir.resolve()
        if not dataset_dir.is_dir():
            raise SystemExit(f"Dataset directory not found: {dataset_dir}")
        output_path = _write_croissant(
            dataset_dir=dataset_dir,
            output=args.output,
            dataset_name=args.name,
            dataset_description=args.description,
            dataset_url=args.url,
            license_url=args.license,
        )
        print(output_path)
        return

    if args.family_dir is not None:
        family_dir = args.family_dir.resolve()
        if not family_dir.is_dir():
            raise SystemExit(f"Family directory not found: {family_dir}")
        output_path = _write_family_croissant(
            family_dir=family_dir,
            output=args.output,
            dataset_name=args.name,
            dataset_description=args.description,
            dataset_url=args.url,
            license_url=args.license,
        )
        print(output_path)
        return

    suite_dir = args.suite_dir.resolve()
    if not suite_dir.is_dir():
        raise SystemExit(f"Suite directory not found: {suite_dir}")
    if args.output is not None or args.name is not None or args.description is not None:
        raise SystemExit("--output, --name, and --description are only supported with --dataset-dir or --family-dir")

    family_dirs = _iter_family_dirs(suite_dir)
    if not family_dirs:
        raise SystemExit(f"No benchmark families found under: {suite_dir}")
    for family_dir in family_dirs:
        output_path = _write_family_croissant(
            family_dir=family_dir,
            output=None,
            dataset_name=None,
            dataset_description=None,
            dataset_url=args.url,
            license_url=args.license,
        )
        print(output_path)


if __name__ == "__main__":
    main()
